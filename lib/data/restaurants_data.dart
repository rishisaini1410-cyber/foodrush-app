Dish _dish(String name, int price, String note, String image,
    [List<String> tags = const []]) {
  return Dish(
    name: name,
    price: price,
    note: note,
    image: image,
    tags: tags,
  );
}

List<MenuItem> _buildMenu(
  String restaurantId,
  String diet,
  List<Dish> items, {
  int bestIndex = 0,
}) {
  return List.generate(items.length, (index) {
    return MenuItem.fromDish(
      id: '$restaurantId-${index + 1}',
      diet: diet,
      best: index == bestIndex,
      dish: items[index],
    );
  });
}

Restaurant _restaurant({
  required String id,
  required String name,
  required String category,
  required String time,
  required String rating,
  required String zone,
  required String diet,
  required String image,
  required List<String> tags,
  required List<Dish> items,
  required double distanceKm,
  int bestIndex = 0,
}) {
  return Restaurant(
    id: id,
    name: name,
    category: category,
    time: time,
    rating: rating,
    zone: zone,
    diet: diet,
    image: image,
    tags: tags,
    distanceKm: distanceKm,
    menu: _buildMenu(id, diet, items, bestIndex: bestIndex),
  );
}

