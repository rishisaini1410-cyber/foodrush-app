List<Dish> _vegMenu(String prefix, List<String> names) {
  return List.generate(15, (i) {
    final name = names[i % names.length];
    final label = i < names.length ? name : '$prefix $name';
    return _dish(
      label,
      89 + ((i + 1) * 13) % 140,
      'Fresh $name — ghar jaisa swad',
      _vegPhotos[i % _vegPhotos.length],
      ['Veg', prefix.split(' ').first],
    );
  });
}

